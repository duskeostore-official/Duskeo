create extension if not exists pgcrypto;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null unique,
  price integer not null check (price >= 0),
  theme text not null check (theme in ('Anime', 'Samurai', 'Mythic')),
  launched_at date not null,
  card_alt text not null default '',
  description text not null,
  kicker text not null default 'DUSKEO / GRAPHIC COLLECTION',
  photos jsonb not null default '[]'::jsonb,
  specs jsonb not null default '[]'::jsonb,
  is_dummy boolean not null default false,
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory (
  product_id uuid not null references public.products(id) on delete cascade,
  size text not null check (size in ('S', 'M', 'L', 'XL', 'XXL')),
  quantity integer not null default 0 check (quantity >= 0),
  updated_at timestamptz not null default now(),
  primary key (product_id, size)
);

create table if not exists public.restock_requests (
  id bigint generated by default as identity primary key,
  product text not null check (length(trim(product)) > 0),
  size text not null check (size in ('S', 'M', 'L', 'XL', 'XXL')),
  email text not null,
  requested_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid()
  );
$$;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
before update on public.products
for each row execute function public.set_updated_at();

drop trigger if exists inventory_set_updated_at on public.inventory;
create trigger inventory_set_updated_at
before update on public.inventory
for each row execute function public.set_updated_at();

alter table public.products enable row level security;
alter table public.inventory enable row level security;
alter table public.restock_requests enable row level security;
alter table public.admin_users enable row level security;

create policy "Public can read products"
on public.products for select
using (not is_deleted);

create policy "Admins can manage products"
on public.products for all
using (public.is_admin())
with check (public.is_admin());

create policy "Public can read inventory"
on public.inventory for select
to anon, authenticated
using (true);

create policy "Admins can manage inventory"
on public.inventory for all
to authenticated
using (public.is_admin())
with check (public.is_admin());

create policy "Anyone can create restock requests"
on public.restock_requests for insert
to anon, authenticated
with check (length(trim(email)) > 0);

create policy "Admins can read restock requests"
on public.restock_requests for select
to authenticated
using (public.is_admin());

create policy "Admins can read admin users"
on public.admin_users for select
to authenticated
using (public.is_admin());

