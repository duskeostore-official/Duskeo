insert into public.inventory (product_id, size, quantity)
select p.id, s.size, 0
from public.products p
cross join (values ('S'), ('M'), ('L'), ('XL'), ('XXL')) as s(size)
on conflict do nothing;

create or replace function public.take_inventory(product_name text, size_name text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_rows integer;
begin
  update public.inventory i
  set quantity = quantity - 1
  from public.products p
  where i.product_id = p.id
    and p.name = product_name
    and i.size = size_name
    and i.quantity > 0
    and not p.is_deleted;
  get diagnostics updated_rows = row_count;
  return updated_rows = 1;
end;
$$;

grant execute on function public.take_inventory(text, text) to anon, authenticated;
