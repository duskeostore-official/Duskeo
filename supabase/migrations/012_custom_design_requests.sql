create table if not exists public.custom_design_requests (
  id bigint generated by default as identity primary key,
  customer_name text not null check (length(trim(customer_name)) between 2 and 100),
  email text not null check (length(trim(email)) between 3 and 254),
  phone text check (phone is null or length(trim(phone)) <= 30),
  garment text not null check (garment in ('T-shirt', 'Hoodie', 'Other')),
  size text check (size is null or size in ('S', 'M', 'L', 'XL', 'XXL')),
  details text not null check (length(trim(details)) between 10 and 2000),
  image_path text,
  status text not null default 'new' check (status in ('new', 'reviewing', 'contacted', 'closed')),
  created_at timestamptz not null default now()
);

alter table public.custom_design_requests enable row level security;

grant insert (customer_name, email, phone, garment, size, details, image_path)
  on public.custom_design_requests to anon, authenticated;
grant select on public.custom_design_requests to authenticated;
grant update (status) on public.custom_design_requests to authenticated;

create policy "Anyone can submit a custom design request"
on public.custom_design_requests for insert
to anon, authenticated
with check (
  length(trim(customer_name)) between 2 and 100
  and length(trim(email)) between 3 and 254
  and garment in ('T-shirt', 'Hoodie', 'Other')
  and (size is null or size in ('S', 'M', 'L', 'XL', 'XXL'))
  and length(trim(details)) between 10 and 2000
);

create policy "Admins can read custom design requests"
on public.custom_design_requests for select
to authenticated
using (public.is_admin());

create policy "Admins can update custom design request status"
on public.custom_design_requests for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'custom-design-requests',
  'custom-design-requests',
  false,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

create policy "Anyone can upload custom design references"
on storage.objects for insert
to anon, authenticated
with check (bucket_id = 'custom-design-requests');

create policy "Admins can read custom design references"
on storage.objects for select
to authenticated
using (bucket_id = 'custom-design-requests' and public.is_admin());
